//! Build script: embeds the application icon and version info into lumen.exe.
//!
//! Without this the executable gets the generic Windows program icon in
//! Explorer, the taskbar and Alt-Tab, because the icon painted at runtime
//! (`icons::app_icon`) is only used for the window itself.
//!
//! The resource is compiled with `rc.exe` from the Windows SDK, which ships
//! with the MSVC toolchain. It is located by looking at the usual install
//! folders instead of asking the registry, so the build works in sandboxes that
//! forbid `reg.exe`. When no resource compiler can be found the build continues
//! with a warning rather than failing: the executable still runs, it just has no
//! icon.
//!
//! The icon itself is generated by `tools/make_icon.py`; re-run that script
//! after changing the logo.

use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    println!("cargo:rerun-if-changed=assets/lumen.ico");
    println!("cargo:rerun-if-changed=assets/lumen.rc");
    println!("cargo:rerun-if-changed=build.rs");

    if std::env::var_os("CARGO_CFG_WINDOWS").is_none() {
        return;
    }

    let Some(rc) = find_resource_compiler() else {
        println!(
            "cargo:warning=rc.exe was not found, so lumen.exe will have no icon; \
             install the Windows SDK to embed it"
        );
        return;
    };

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR is always set by cargo"));
    let resource = out_dir.join("lumen.res");

    let status = Command::new(&rc)
        .arg("/nologo")
        .arg(format!("/fo{}", resource.display()))
        .arg("assets/lumen.rc")
        .status();

    match status {
        Ok(status) if status.success() && resource.exists() => {
            // The MSVC linker accepts a compiled resource file directly.
            println!("cargo:rustc-link-arg={}", resource.display());
        }
        Ok(status) => println!("cargo:warning=rc.exe failed ({status}), no icon will be embedded"),
        Err(error) => println!("cargo:warning=could not run rc.exe: {error}"),
    }
}

/// Finds the newest `rc.exe` in the Windows SDK install folders.
fn find_resource_compiler() -> Option<PathBuf> {
    // An explicit path wins, which is handy on build machines with an unusual
    // SDK layout.
    if let Some(path) = std::env::var_os("LUMEN_RC") {
        let path = PathBuf::from(path);
        if path.is_file() {
            return Some(path);
        }
    }

    if let Some(path) = which("rc.exe") {
        return Some(path);
    }

    let kits = std::env::var_os("ProgramFiles(x86)")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from(r"C:\Program Files (x86)"))
        .join("Windows Kits")
        .join("10")
        .join("bin");

    // Version folders sort correctly as strings because they are numeric with
    // the same number of components; take the highest one that has an rc.exe.
    let mut versions: Vec<PathBuf> = std::fs::read_dir(&kits)
        .ok()?
        .flatten()
        .map(|entry| entry.path())
        .filter(|path| path.is_dir())
        .collect();
    versions.sort();
    for version in versions.into_iter().rev() {
        for host in ["x64", "x86"] {
            let candidate = version.join(host).join("rc.exe");
            if candidate.is_file() {
                return Some(candidate);
            }
        }
    }
    None
}

/// Looks a program up on `PATH`.
fn which(program: &str) -> Option<PathBuf> {
    let paths = std::env::var_os("PATH")?;
    std::env::split_paths(&paths)
        .map(|folder| folder.join(program))
        .find(|candidate| is_executable(candidate))
}

fn is_executable(path: &Path) -> bool {
    path.is_file()
}
